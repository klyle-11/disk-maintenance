#!/bin/bash

echo "========== 🐍 PYTHON CACHE (grouped by project) =========="

find . -type d -name "__pycache__" -print0 | while IFS= read -r -d '' dir; do
  # Normalize path
  clean="${dir#./}"
  project=$(echo "$clean" | cut -d'/' -f1)

  # Size (KB)
  size_kb=$(du -sk "$dir" 2>/dev/null | awk '{print $1}')

  # Modified time
  mtime=$(stat -f "%m" "$dir" 2>/dev/null || stat -c "%Y" "$dir")

  echo "$project|$size_kb|$mtime"
done | awk -F'|' '
{
  size[$1] += $2
  if ($3 > max_time[$1]) {
    max_time[$1] = $3
  }
}
END {
  for (proj in size) {
    print size[proj] "|" max_time[proj] "|./" proj
  }
}' | sort -nr | while IFS='|' read -r size_kb mtime project; do
  size_hr=$(echo "$size_kb * 1024" | awk '{ split("B KB MB GB TB", u); for(i=5; x<1; i--) x=$1/1024^(i-1); printf "%.1f%s\n", x, u[i] }')
  date_hr=$(date -r "$mtime" "+%Y-%m-%d")
  printf "%-8s  %-12s  %s\n" "$size_hr" "$date_hr" "$project"
done


echo ""
echo "========== 📦 NODE MODULES =========="

find . -type d -name "node_modules" -print0 | while IFS= read -r -d '' dir; do

  # Skip nested node_modules
  if [[ "$dir" == *node_modules/*node_modules* ]]; then
    continue
  fi

  size_kb=$(du -sk "$dir" 2>/dev/null | awk '{print $1}')
  size_hr=$(du -sh "$dir" 2>/dev/null | cut -f1)

  mtime=$(stat -f "%m" "$dir" 2>/dev/null || stat -c "%Y" "$dir")
  htime=$(date -r "$mtime" "+%Y-%m-%d")

  echo "$size_kb|$size_hr|$htime|$dir"
done | sort -nr | awk -F'|' '{printf "%-8s  %-12s  %s\n", $2, $3, $4}'